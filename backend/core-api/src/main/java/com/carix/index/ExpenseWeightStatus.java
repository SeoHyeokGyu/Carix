package com.carix.index;

/**
 * 소비 가중치의 출처. 도메인 정의서 §1.2 가 이 4종으로 고정했다 — {@code SEMI_ESTIMATED} 같은 다른 표기를 쓰지 않는다.
 *
 * <p>도메인 정의서 §1.1 은 상태를 카테고리 단위로 도출하고 월 요약을 롤업으로 정의한다. 이 계약은 월 요약만 받는다 — 대시보드 뱃지가 월 단위이기 때문이다.
 * 카테고리별 상태가 필요해지면 이 계약을 넓힌다.
 */
public enum ExpenseWeightStatus {
  /** 내 지출 기준. 6개 카테고리를 모두 입력했고 합계가 0보다 크다. */
  USER_DEFINED,

  /** 일부 추정 포함. 입력과 기본값이 섞였다. */
  PARTIALLY_ESTIMATED,

  /** 이전 지출 기준. 해당 월 입력이 없어 가장 가까운 과거 월을 상속했다. */
  PROPAGATED,

  /** 통계청 평균 기준. 과거 이력이 없어 기본 가중치로 대체했다. */
  DEFAULT_CPI
}
